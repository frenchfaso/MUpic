#!/usr/bin/env python3
"""Bundle dependency notices from checksum-verified Cargo archives (no network).

Run after `cargo fetch --locked` for encoder and demo/emulator. Extra Cargo
caches may be supplied with --cargo-home. --check verifies the published file.
"""
import argparse
import hashlib
import os
from pathlib import Path
import tarfile
import tomllib

ROOT = Path(__file__).resolve().parents[1]
LOCKS = ('encoder/Cargo.lock', 'demo/emulator/Cargo.lock')
OUTPUT = ROOT / 'site/licenses/rust-dependencies.txt'


def collect(homes):
    packages = {}
    for name in LOCKS:
        for package in tomllib.loads((ROOT / name).read_text())['package']:
            if 'source' not in package:
                continue  # Vendored sources retain their own notices.
            if package['source'] != 'registry+https://github.com/rust-lang/crates.io-index':
                raise ValueError(f'Unsupported dependency source: {package["source"]}')
            key = (package['name'], package['version'])
            if key in packages and packages[key]['checksum'] != package['checksum']:
                raise ValueError(f'Conflicting package checksums: {key}')
            packages[key] = package
    texts, records = {}, []
    for (name, version), package in sorted(packages.items()):
        archives = [p for home in homes for p in home.glob(f'registry/cache/*/{name}-{version}.crate')]
        if not archives:
            raise ValueError(f'Missing {name}-{version}.crate; run cargo fetch --locked first')
        if hashlib.sha256(archives[0].read_bytes()).hexdigest() != package['checksum']:
            raise ValueError(f'Cargo archive checksum mismatch: {name}-{version}')
        prefix = f'{name}-{version}/'
        notices = []
        with tarfile.open(archives[0]) as archive:
            manifest = tomllib.loads(archive.extractfile(prefix + 'Cargo.toml').read().decode())['package']
            for member in sorted(archive.getmembers(), key=lambda m: m.name):
                path = Path(member.name.removeprefix(prefix))
                if not member.isfile() or not member.name.startswith(prefix):
                    continue
                if not (path.name.upper().startswith(('LICENSE', 'LICENCE', 'COPYING', 'COPYRIGHT', 'NOTICE', 'UNLICENSE', 'AUTHORS'))
                        or any(part.upper() in ('LICENSES', 'LICENCES') for part in path.parts)
                        or str(path) == manifest.get('license-file')):
                    continue
                content = archive.extractfile(member).read().decode('utf-8').replace('\r\n', '\n').strip() + '\n'
                digest = hashlib.sha256(content.encode()).hexdigest()
                texts.setdefault(digest, content)
                notices.append((str(path), digest))
        if not notices:
            raise ValueError(f'No license notices found for {name}-{version}')
        records.append((name, version, manifest.get('license', 'See license file'), package['checksum'], notices))
    # Deduplicate identical texts, including the Apache license, while retaining
    # every package's copyright statements and original notice filenames.
    numbers = {digest: index + 1 for index, digest in enumerate(texts)}
    lines = ['MUpic: Rust dependency licenses and copyright notices',
             'Generated by tools/collect_licenses.py from the two checked-in Cargo.lock files.',
             'Includes build/test and platform dependencies; not every package enters the WASM binaries.',
             'Vendored emulator code and Rust standard-library notices are distributed separately.',
             'License alternatives (OR) remain alternatives; this inventory does not relicense dependencies.', '']
    for lock in LOCKS:
        lines.append(f'{lock} SHA-256: {hashlib.sha256((ROOT / lock).read_bytes()).hexdigest()}')
    for name, version, license_name, checksum, notices in records:
        lines.extend(['', f'{name} {version} — {license_name}',
                      f'Source: https://crates.io/crates/{name}/{version}', f'Archive SHA-256: {checksum}'])
        lines.extend(f'  {path}: text {numbers[digest]}' for path, digest in notices)
    for digest, content in texts.items():
        lines.extend(['', '=' * 72, f'Text {numbers[digest]}', '=' * 72, content.rstrip()])
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cargo-home', action='append', type=Path, default=[])
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    homes = [Path(os.environ.get('CARGO_HOME', Path.home() / '.cargo')), *args.cargo_home]
    result = collect(homes)
    if args.check:
        if OUTPUT.read_text() != result:
            raise SystemExit('Dependency notices are stale; rerun tools/collect_licenses.py')
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(result)
    print(f'{OUTPUT.relative_to(ROOT)}: {len(result.encode()):,} bytes')


if __name__ == '__main__':
    main()
